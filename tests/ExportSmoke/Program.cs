using Topdf;
var root = Path.GetFullPath(Path.Combine("artifacts", "export-test", Guid.NewGuid().ToString("N")));
Directory.CreateDirectory(root);
var first = Path.Combine(root, "first.pdf"); var second = Path.Combine(root, "second.pdf");
File.WriteAllBytes(first, "%PDF-1.7\nfirst fixture"u8.ToArray());
File.WriteAllBytes(second, "%PDF-1.7\nsecond fixture"u8.ToArray());
var output = Path.Combine(root, "saved");
var checkedItems = new[] { new PdfExportItem("same.docx",first), new PdfExportItem("same.xlsx",second), new PdfExportItem("same.docx",second), new PdfExportItem("pending.hwp",null), new PdfExportItem("missing.dwg",Path.Combine(root,"missing.pdf")) };
var report = PdfExportService.Export(checkedItems, output);
if (report.Saved.Count!=3 || report.Skipped.Count!=1 || report.Errors.Count!=1) throw new Exception("Incorrect batch results");
if (!File.ReadAllBytes(Path.Combine(output,"same.docx.pdf")).SequenceEqual(File.ReadAllBytes(first))) throw new Exception("Wrong export content");
if (!File.ReadAllBytes(Path.Combine(output,"same.docx (2).pdf")).SequenceEqual(File.ReadAllBytes(second))) throw new Exception("Filename collision lost content");
if (File.Exists(Path.Combine(output,"missing.dwg.pdf"))) throw new Exception("Partial failed output retained");
var again = PdfExportService.Export(new[] { new PdfExportItem("same.docx",second) }, output);
if (!again.Saved.Single().EndsWith("same.docx (3).pdf")) throw new Exception("Existing file overwritten");
var original = File.ReadAllBytes(first);
var protect = PdfExportService.Export(new[] { new PdfExportItem(first,first) },root);
if (protect.Saved.Single()==first || !File.ReadAllBytes(first).SequenceEqual(original)) throw new Exception("Source PDF modified");
Console.WriteLine("PASS: batch subset, identical basenames across formats, collisions without overwrite, pending skip, per-file failure continuation, original PDF protection.");
Console.WriteLine(root);
